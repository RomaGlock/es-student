// Мигание встроенным светодиодом Pico целиком на ассемблере, без вызовов SDK:
// настройка вывода, суперцикл и задержки — внутри одной вставки.
//
// Адреса регистров — RP2040 Datasheet: 2.19.6.1 (IO_BANK0), 2.19.6.3 (PADS_BANK0),
// 2.3.1 (SIO). Смещения +0x2000 и +0x3000 — атомарные псевдонимы SET и CLR.

int main()
{
    asm volatile(
        ".syntax unified\n"

        // --- то, что делали gpio_init() и gpio_set_dir() ---
        "   ldr  r0, =0x4001e068\n" // PADS_BANK0, вывод 25, псевдоним SET
        "   movs r1, #0x40\n"
        "   str  r1, [r0]\n"        // IE = 1 — входной буфер включён
        "   ldr  r0, =0x4001f068\n" // тот же регистр, псевдоним CLR
        "   movs r1, #0x80\n"
        "   str  r1, [r0]\n"        // OD = 0 — выходной буфер разрешён
        "   ldr  r0, =0x400140cc\n" // IO_BANK0: GPIO25_CTRL
        "   movs r1, #5\n"
        "   str  r1, [r0]\n"        // FUNCSEL = 5 — выводом управляет SIO

        "   movs r0, #0xd0\n"
        "   lsls r0, r0, #24\n"     // r0 = 0xd0000000 — база SIO
        "   movs r1, #1\n"
        "   lsls r1, r1, #25\n"     // r1 = 1 << 25 — маска GPIO25
        "   str  r1, [r0, #0x24]\n" // GPIO_OE_SET — вывод работает на выход

        // --- мигание ---
        "3: str  r1, [r0, #0x14]\n" // GPIO_OUT_SET — включить светодиод
        "   ldr  r2, =10500000\n"   // 250 мс
        "1: subs r2, #1\n"
        "   bne  1b\n"
        "   str  r1, [r0, #0x18]\n" // GPIO_OUT_CLR — выключить светодиод
        "   ldr  r2, =42000000\n"   // 1000 мс
        "2: subs r2, #1\n"
        "   bne  2b\n"
        "   b    3b\n"              // суперцикл

        ".ltorg\n"                  // пул констант для команд ldr =...
        :
        :
        : "r0", "r1", "r2", "cc", "memory");
}
